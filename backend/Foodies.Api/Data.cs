using Microsoft.EntityFrameworkCore;
namespace Foodies.Api;
public class FoodiesDb(DbContextOptions<FoodiesDb> options) : DbContext(options) {
    public DbSet<PlatformAdmin> PlatformAdmins => Set<PlatformAdmin>();
    public DbSet<User> Users => Set<User>(); public DbSet<Store> Stores => Set<Store>();
    public DbSet<Membership> Memberships => Set<Membership>(); public DbSet<Category> Categories => Set<Category>();
    public DbSet<Dish> Dishes => Set<Dish>(); public DbSet<Order> Orders => Set<Order>();
    public DbSet<PhoneCode> PhoneCodes => Set<PhoneCode>(); public DbSet<SmsDelivery> SmsDeliveries => Set<SmsDelivery>();
    protected override void OnModelCreating(ModelBuilder m) {
        // IDs are generated by our entities. New children added to a tracked aggregate
        // must be INSERTed, even though their Guid is already populated.
        foreach (var type in new[] { typeof(PlatformAdmin), typeof(User), typeof(Store), typeof(BusinessHour), typeof(Membership), typeof(Category), typeof(Dish), typeof(Order), typeof(OrderItem), typeof(StatusHistory), typeof(PhoneCode), typeof(SmsDelivery) })
            m.Entity(type).Property("Id").ValueGeneratedNever();
        m.Entity<User>().HasIndex(x => x.GoogleSubject).IsUnique(); m.Entity<Store>().HasIndex(x => x.Slug).IsUnique();
        m.Entity<PlatformAdmin>().HasIndex(x => x.Email).IsUnique();
        m.Entity<Store>().HasMany(x => x.Hours).WithOne().HasForeignKey(x => x.StoreId).OnDelete(DeleteBehavior.Cascade);
        m.Entity<Membership>().HasIndex(x => new { x.StoreId, x.UserId }).IsUnique();
        m.Entity<Membership>().HasOne<User>().WithMany().HasForeignKey(x => x.UserId).OnDelete(DeleteBehavior.Restrict);
        m.Entity<Membership>().HasOne<Store>().WithMany().HasForeignKey(x => x.StoreId).OnDelete(DeleteBehavior.Restrict);
        m.Entity<Category>().HasAlternateKey(x => new { x.StoreId, x.Id });
        m.Entity<Category>().HasOne<Store>().WithMany().HasForeignKey(x => x.StoreId).OnDelete(DeleteBehavior.Restrict);
        m.Entity<Dish>().HasOne<Category>().WithMany().HasForeignKey(x => new { x.StoreId, x.CategoryId }).HasPrincipalKey(x => new { x.StoreId, x.Id }).OnDelete(DeleteBehavior.Restrict);
        m.Entity<Dish>().HasIndex(x => new { x.StoreId, x.IsActive, x.SortOrder });
        m.Entity<Order>().HasOne<Store>().WithMany().HasForeignKey(x => x.StoreId).OnDelete(DeleteBehavior.Restrict);
        m.Entity<Order>().HasOne<User>().WithMany().HasForeignKey(x => x.CustomerUserId).OnDelete(DeleteBehavior.Restrict);
        m.Entity<Order>().HasIndex(x => new { x.CustomerUserId, x.IdempotencyKey }).IsUnique();
        m.Entity<Order>().HasIndex(x => x.PublicCode).IsUnique();
        m.Entity<Order>().HasIndex(x => new { x.StoreId, x.Status, x.CreatedAt });
        m.Entity<Order>().HasIndex(x => new { x.CustomerUserId, x.CreatedAt });
        m.Entity<Order>().HasMany(x => x.Items).WithOne().HasForeignKey(x => x.OrderId);
        m.Entity<Order>().HasMany(x => x.History).WithOne().HasForeignKey(x => x.OrderId);
        m.Entity<OrderItem>().HasOne<Dish>().WithMany().HasForeignKey(x => x.DishId).OnDelete(DeleteBehavior.Restrict);
        m.Entity<PhoneCode>().HasOne<User>().WithMany().HasForeignKey(x => x.UserId).OnDelete(DeleteBehavior.Restrict);
        m.Entity<PhoneCode>().HasIndex(x => new { x.UserId, x.CreatedAt });
        m.Entity<SmsDelivery>().HasOne<Order>().WithMany().HasForeignKey(x => x.OrderId).OnDelete(DeleteBehavior.Restrict);
        m.Entity<SmsDelivery>().HasIndex(x => new { x.OrderId, x.TemplateType }).IsUnique();
        foreach (var entity in m.Model.GetEntityTypes()) foreach (var p in entity.GetProperties())
            if (p.ClrType == typeof(decimal)) { p.SetPrecision(18); p.SetScale(2); }
    }
}
